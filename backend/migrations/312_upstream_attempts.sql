CREATE TABLE IF NOT EXISTS upstream_attempts (
    id BIGSERIAL PRIMARY KEY,
    attempt_id VARCHAR(128) NOT NULL UNIQUE,
    request_id VARCHAR(256) NOT NULL DEFAULT '',
    client_request_id VARCHAR(256) NOT NULL DEFAULT '',
    upstream_request_id VARCHAR(256) NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    user_id BIGINT,
    group_id BIGINT,
    account_id BIGINT NOT NULL,
    model VARCHAR(256) NOT NULL DEFAULT '',
    protocol VARCHAR(64) NOT NULL,
    source VARCHAR(32) NOT NULL,
    service_tier VARCHAR(64) NOT NULL DEFAULT '',
    reasoning_effort VARCHAR(64) NOT NULL DEFAULT '',
    long_context_pricing_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    http_status INTEGER NOT NULL DEFAULT 0 CHECK (http_status >= 0 AND http_status <= 999),
    outcome VARCHAR(16) NOT NULL,
    usage_present BOOLEAN NOT NULL DEFAULT FALSE,
    input_tokens BIGINT CHECK (input_tokens >= 0),
    cache_creation_tokens BIGINT CHECK (cache_creation_tokens >= 0),
    cache_read_tokens BIGINT CHECK (cache_read_tokens >= 0),
    cache_creation_5m_tokens BIGINT CHECK (cache_creation_5m_tokens >= 0),
    cache_creation_1h_tokens BIGINT CHECK (cache_creation_1h_tokens >= 0),
    output_tokens BIGINT CHECK (output_tokens >= 0),
    reasoning_tokens BIGINT CHECK (reasoning_tokens >= 0),
    account_rate_multiplier NUMERIC(20, 10) NOT NULL CHECK (account_rate_multiplier >= 0),
    cost_usd NUMERIC(20, 10),
    cost_status VARCHAR(32) NOT NULL,
    CHECK (source IN ('request', 'recovery_probe', 'channel_monitor', 'channel_monitor_v3', 'openai_iq')),
    CHECK (outcome IN ('success', 'failed', 'incomplete', 'unknown')),
    CHECK (cost_status IN ('known', 'unknown_pricing', 'no_usage')),
    CHECK ((cost_status = 'known') = (cost_usd IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_upstream_attempts_account_time ON upstream_attempts (account_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_upstream_attempts_client_request_source ON upstream_attempts (client_request_id, source);
